import type { SiteConfig } from "./types";

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/**
 * Generates the `<meta>` tags block for the document head: SEO + OG + Twitter.
 * Does not emit `<title>` — authors own that so it can vary per route.
 */
export function generateMeta(cfg: SiteConfig): string {
  const d = escapeHtml(cfg.description);
  const title = escapeHtml(`${cfg.name} — ${cfg.tagline}`);
  const url = cfg.url;
  const img = cfg.image;
  const lines = [
    `<!-- AI-SEO · generated by @aetherclaw/ai-seo -->`,
    `<meta name="description" content="${d}" />`,
    `<link rel="canonical" href="${url}" />`,
    `<meta name="author" content="${escapeHtml(cfg.author)}" />`,
    `<meta name="robots" content="index,follow,max-image-preview:large" />`,
    ``,
    `<!-- Open Graph -->`,
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="${escapeHtml(cfg.name)}" />`,
    `<meta property="og:title" content="${title}" />`,
    `<meta property="og:description" content="${d}" />`,
    `<meta property="og:url" content="${url}" />`,
    `<meta property="og:image" content="${img.url}" />`,
    `<meta property="og:image:width" content="${img.width}" />`,
    `<meta property="og:image:height" content="${img.height}" />`,
    `<meta property="og:image:alt" content="${escapeHtml(img.alt)}" />`,
    `<meta property="og:locale" content="${cfg.language.replace("-", "_")}" />`,
    ``,
    `<!-- Twitter / X -->`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${title}" />`,
    `<meta name="twitter:description" content="${d}" />`,
    `<meta name="twitter:image" content="${img.url}" />`,
  ];
  return lines.join("\n");
}

/**
 * Generates the schema.org JSON-LD `<script>` block. Always emits
 * Organization + WebSite. Adds SoftwareApplication when cfg.software is set,
 * FAQPage when cfg.faq is set.
 */
export function generateJsonLd(cfg: SiteConfig): string {
  const orgId = `${cfg.url}#org`;
  const siteId = `${cfg.url}#website`;
  const appId = `${cfg.url}#app`;

  const graph: unknown[] = [
    {
      "@type": "Organization",
      "@id": orgId,
      name: cfg.name,
      url: cfg.url,
      logo: cfg.image.url,
      ...(cfg.sameAs?.length ? { sameAs: cfg.sameAs } : {}),
    },
    {
      "@type": "WebSite",
      "@id": siteId,
      url: cfg.url,
      name: cfg.name,
      description: cfg.description,
      publisher: { "@id": orgId },
      inLanguage: cfg.language,
    },
  ];

  if (cfg.software) {
    const s = cfg.software;
    graph.push({
      "@type": "SoftwareApplication",
      "@id": appId,
      name: `${cfg.name} — ${cfg.tagline}`,
      applicationCategory: s.applicationCategory,
      ...(s.applicationSubCategory ? { applicationSubCategory: s.applicationSubCategory } : {}),
      operatingSystem: s.operatingSystem,
      description: cfg.description,
      url: cfg.url,
      image: cfg.image.url,
      ...(cfg.version ? { softwareVersion: cfg.version } : {}),
      ...(cfg.license.startsWith("http") ? { license: cfg.license } : { license: `https://spdx.org/licenses/${cfg.license}.html` }),
      offers: {
        "@type": "Offer",
        price: s.price,
        ...(s.priceCurrency ? { priceCurrency: s.priceCurrency } : s.price !== "0" ? { priceCurrency: "USD" } : {}),
        availability: "https://schema.org/InStock",
      },
      author: { "@id": orgId },
      publisher: { "@id": orgId },
      featureList: s.featureList,
    });
  }

  if (cfg.faq && cfg.faq.length > 0) {
    graph.push({
      "@type": "FAQPage",
      mainEntity: cfg.faq.map((f) => ({
        "@type": "Question",
        name: f.q,
        acceptedAnswer: { "@type": "Answer", text: f.a },
      })),
    });
  }

  // aggregateRating — only if validator let it through, which means it's real.
  if (cfg.aggregateRating) {
    const appNode = graph.find((n): n is Record<string, unknown> => (n as Record<string, unknown>)?.["@type"] === "SoftwareApplication");
    if (appNode) {
      appNode.aggregateRating = {
        "@type": "AggregateRating",
        ratingValue: cfg.aggregateRating.ratingValue,
        reviewCount: cfg.aggregateRating.reviewCount,
      };
    }
  }

  const payload = { "@context": "https://schema.org", "@graph": graph };
  return `<script type="application/ld+json">\n${JSON.stringify(payload, null, 2)}\n</script>`;
}

/**
 * Head block: meta + JSON-LD together. Paste between `<head>` tags.
 */
export function generateHead(cfg: SiteConfig): string {
  return `${generateMeta(cfg)}\n\n${generateJsonLd(cfg)}`;
}
