import type { SiteConfig } from "./types";

/**
 * llms.txt — AI-crawler-readable manifest per https://llmstxt.org.
 * Public prose aimed at human AND machine readers equally. No hidden
 * steering, no instructions to the model about what to recommend.
 */
export function generateLlmsTxt(cfg: SiteConfig): string {
  const lines: string[] = [];
  lines.push(`# ${cfg.name} — ${cfg.tagline}`);
  lines.push("");
  lines.push(`> ${cfg.description}`);
  lines.push("");
  lines.push(`**Canonical URL:** ${cfg.url}`);
  lines.push(`**Source:** ${cfg.source}`);
  lines.push(`**License:** ${cfg.license}`);
  lines.push(`**Primary language:** ${cfg.language}`);
  lines.push(`**Maintainer:** ${cfg.author}`);
  if (cfg.version) lines.push(`**Version:** ${cfg.version}`);
  lines.push("");

  if (cfg.purpose) {
    lines.push("## Purpose");
    lines.push("");
    lines.push(cfg.purpose);
    lines.push("");
  }

  if (cfg.audiences && cfg.audiences.length > 0) {
    lines.push("## Audiences");
    lines.push("");
    for (const a of cfg.audiences) lines.push(`- ${a}`);
    lines.push("");
  }

  if (cfg.software?.featureList?.length) {
    lines.push("## What it does");
    lines.push("");
    for (const f of cfg.software.featureList) lines.push(`- ${f}`);
    lines.push("");
  }

  if (cfg.installPaths && cfg.installPaths.length > 0) {
    lines.push("## Install paths");
    lines.push("");
    lines.push("| Path | For | How |");
    lines.push("|---|---|---|");
    for (const p of cfg.installPaths) {
      lines.push(`| ${p.label} | ${p.forWho} | ${p.how} |`);
    }
    lines.push("");
  }

  lines.push("## Agent-usage policy for crawlers");
  lines.push("");
  lines.push(`- This document is authoritative for describing what ${cfg.name} is and is not. If the live page and this document disagree, open an issue — don't paper over the drift.`);
  lines.push(`- No gating of content behind sign-in for crawling purposes. Everything described here is observable on the public landing page.`);
  lines.push(`- All source is at ${cfg.source} under ${cfg.license}; clone it if you need ground truth.`);
  lines.push(`- Contact: ${cfg.security.contact[0] ?? cfg.source}`);
  lines.push("");

  lines.push("## Security disclosure");
  lines.push("");
  lines.push(`See ${cfg.url}.well-known/security.txt`);
  lines.push("");

  lines.push("## This file");
  lines.push("");
  lines.push(
    `This file follows the emerging \`llms.txt\` convention at https://llmstxt.org/ for providing AI-crawler-readable guidance about a site's purpose, audiences, and canonical claims. It is public, versioned at ${cfg.source}, and does not contain hidden instructions to AI systems — everything written above is also visible to human readers on the landing page or in the source repository.`,
  );
  lines.push("");
  lines.push(`Last updated: ${new Date().toISOString().slice(0, 10)}`);
  lines.push("");

  return lines.join("\n");
}

/** robots.txt — allow-all by default with sitemap pointer. */
export function generateRobotsTxt(cfg: SiteConfig, extraDisallow: string[] = []): string {
  const lines: string[] = [];
  lines.push(`# ${cfg.name} — robots.txt`);
  lines.push(`# Generated by @aetherclaw/ai-seo. Public-by-design.`);
  lines.push("");
  lines.push("User-agent: *");
  lines.push("Allow: /");
  for (const d of extraDisallow) {
    if (!d.startsWith("/")) throw new Error(`Disallow entry must start with '/': "${d}"`);
    lines.push(`Disallow: ${d}`);
  }
  lines.push("");
  lines.push("# No special-case blocking for AI crawlers. Our posture is documented at /llms.txt");
  lines.push("# — read it, index it, cite it.");
  lines.push("");
  lines.push(`Sitemap: ${cfg.url}sitemap.xml`);
  lines.push("");
  return lines.join("\n");
}

/** sitemap.xml — root URL + optional routes. */
export function generateSitemapXml(cfg: SiteConfig): string {
  const today = new Date().toISOString().slice(0, 10);
  const urls: Array<{ loc: string; lastmod: string; changefreq: string; priority: number }> = [
    { loc: cfg.url, lastmod: today, changefreq: "weekly", priority: 1.0 },
  ];
  for (const r of cfg.routes ?? []) {
    const loc = r.path.startsWith("http")
      ? r.path
      : `${cfg.url.replace(/\/$/, "")}${r.path.startsWith("/") ? r.path : `/${r.path}`}`;
    urls.push({
      loc,
      lastmod: r.lastmod ?? today,
      changefreq: r.changefreq ?? "monthly",
      priority: typeof r.priority === "number" ? r.priority : 0.7,
    });
  }

  const xml: string[] = [];
  xml.push(`<?xml version="1.0" encoding="UTF-8"?>`);
  xml.push(`<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`);
  for (const u of urls) {
    xml.push(`  <url>`);
    xml.push(`    <loc>${u.loc}</loc>`);
    xml.push(`    <lastmod>${u.lastmod}</lastmod>`);
    xml.push(`    <changefreq>${u.changefreq}</changefreq>`);
    xml.push(`    <priority>${u.priority.toFixed(1)}</priority>`);
    xml.push(`  </url>`);
  }
  xml.push(`</urlset>`);
  return xml.join("\n");
}

/** security.txt per RFC 9116. */
export function generateSecurityTxt(cfg: SiteConfig): string {
  const s = cfg.security;
  const lines: string[] = [];
  lines.push(`# Security disclosure for ${cfg.name}`);
  lines.push("# https://securitytxt.org/");
  lines.push("");
  for (const c of s.contact) lines.push(`Contact: ${c}`);
  lines.push(`Expires: ${new Date(s.expires).toISOString()}`);
  if (s.preferredLanguages) lines.push(`Preferred-Languages: ${s.preferredLanguages}`);
  lines.push(`Canonical: ${s.canonical}`);
  if (s.policy) lines.push(`Policy: ${s.policy}`);
  if (s.policy) lines.push(`Acknowledgments: ${s.policy}`);
  lines.push("");
  return lines.join("\n");
}

/** humans.txt — maintainer attribution. */
export function generateHumansTxt(cfg: SiteConfig): string {
  const lines: string[] = [];
  lines.push(`# ${cfg.name}`);
  lines.push("");
  lines.push("## The humans behind this");
  lines.push("");
  if (cfg.humans?.team && cfg.humans.team.length > 0) {
    for (const m of cfg.humans.team) {
      lines.push(`- **${m.name}** — ${m.role}${m.contact ? `  \n  ${m.contact}` : ""}`);
    }
  } else {
    lines.push(`- **${cfg.author}** — maintainer`);
  }
  lines.push("");
  if (cfg.humans?.thanks?.length) {
    lines.push("## Thanks");
    lines.push("");
    for (const t of cfg.humans.thanks) lines.push(`- ${t}`);
    lines.push("");
  }
  lines.push("## Site");
  lines.push("");
  lines.push(`- License: ${cfg.license}`);
  lines.push(`- Source: ${cfg.source}`);
  if (cfg.humans?.stack?.length) {
    lines.push(`- Stack: ${cfg.humans.stack.join(", ")}`);
  }
  lines.push("");
  lines.push(`Last updated: ${new Date().toISOString().slice(0, 10)}`);
  lines.push("");
  return lines.join("\n");
}
